function stableClientId(parts) {
  const raw = parts.join("|");
  let h1 = 2166136261;
  let h2 = 16777619;
  for (let i = 0; i < raw.length; i += 1) {
    h1 = (h1 ^ raw.charCodeAt(i)) * 16777619 >>> 0;
    h2 = (h2 + raw.charCodeAt(i) * (i + 7)) * 2246822507 >>> 0;
  }
  return `cli_${h1.toString(16)}${h2.toString(16)}_${raw.length}`;
}

